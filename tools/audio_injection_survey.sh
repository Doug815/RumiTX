#!/usr/bin/env bash
# RumiTX 2030 / DOOGEE S80: read-only MediaTek audio route survey.
# Captures snapshots, DOES NOT TRANSMIT, setParameters, key PTT or modify mixer.
set -euo pipefail

LABEL="${1:-idle}"
case "$LABEL" in
  idle|pre_tx|during_tx|after_tx|voice_call_probe) ;;
  *) echo "Usage: $0 [idle|pre_tx|during_tx|after_tx|voice_call_probe]" >&2; exit 2 ;;
esac

command -v adb >/dev/null || { echo "adb is required" >&2; exit 1; }
adb get-state >/dev/null
OUT="${RUMITX_SURVEY_OUT:-$PWD/rumitx-audio-survey}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
DIR="$OUT/${STAMP}_${LABEL}"
mkdir -p "$DIR"
echo "Capturing $LABEL audio-route status to $DIR"

adb shell getprop ro.build.fingerprint > "$DIR/build_fingerprint.txt" 2>&1 || :
adb shell getprop ro.product.device > "$DIR/device.txt" 2>&1 || :
adb shell dumpsys media.audio_flinger > "$DIR/audio_flinger.txt" 2>&1 || :
adb shell dumpsys media.audio_policy > "$DIR/audio_policy.txt" 2>&1 || :
adb shell dumpsys media_session > "$DIR/media_session.txt" 2>&1 || :
adb shell su -c 'id; getenforce 2>/dev/null; cat /proc/asound/cards 2>/dev/null; cat /proc/asound/pcm 2>/dev/null' > "$DIR/alsa_inventory.txt" 2>&1 || :
adb shell su -c '
for f in /proc/asound/card*/pcm*/sub*/status; do
  [ -r "$f" ] || continue
  echo "==== $f ===="
  cat "$f"
done
' > "$DIR/alsa_substream_status.txt" 2>&1 || :
adb shell su -c 'if command -v tinymix >/dev/null 2>&1; then tinymix; else echo "tinymix unavailable"; fi' > "$DIR/tinymix_read_only.txt" 2>&1 || :
adb shell su -c 'ps -A | grep -E "audioserver|mediaserver|rumitx|talkie" || true' > "$DIR/audio_processes.txt" 2>&1 || :
adb logcat -d -t 400 -s RumiTX-TX:I RumiTX-Audio:I RumiTX-HIDL:I > "$DIR/recent_rumitx_audio_log.txt" 2>&1 || :
echo "$STAMP label=$LABEL; read-only capture; no radio transmission generated by this script" > "$DIR/CAPTURE_MANIFEST.txt"

echo "Survey saved: $DIR"
echo "Capture both 'idle' and 'during_tx' separately, then diff the text files."
echo "Local dumps may include identifiers, channel settings, or sensitive device data. Review before sharing."
